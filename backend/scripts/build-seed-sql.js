/**
 * Regenerates database/seed.sql from scripts/seed-data.js.
 * Run with: npm run db:build-seed
 *
 * The generated SQL uses fixed ids because it runs right after schema.sql
 * on empty tables, and relative publish dates (UTC_TIMESTAMP() - INTERVAL …)
 * so the sample stories always look recent.
 */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import mysql from 'mysql2';
import bcrypt from 'bcryptjs';
import { categories, authors, articles } from './seed-data.js';
import { slugify, readingTime, sanitizeContent } from '../src/utils/helpers.js';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const OUT = path.resolve(__dirname, '..', '..', 'database', 'seed.sql');
const e = (v) => (v === null || v === undefined ? 'NULL' : mysql.escape(v));

const DEFAULT_ADMIN = { name: 'Site Admin', email: 'admin@nationalmail.in', password: 'Admin@12345' };

const lines = [];
const out = (s = '') => lines.push(s);

out('-- =====================================================================');
out('--  The National Mail — sample data (generated by scripts/build-seed-sql.js)');
out('--  Run AFTER schema.sql. All people and places in the stories are fictional.');
out(`--  Default admin login: ${DEFAULT_ADMIN.email} / ${DEFAULT_ADMIN.password}  (change it!)`);
out('-- =====================================================================');
out('SET NAMES utf8mb4;');
out("SET time_zone = '+00:00';");
out('START TRANSACTION;');
out();

// users
const hash = bcrypt.hashSync(DEFAULT_ADMIN.password, 10);
out('INSERT INTO users (id, name, email, password_hash, role) VALUES');
out(`  (1, ${e(DEFAULT_ADMIN.name)}, ${e(DEFAULT_ADMIN.email)}, ${e(hash)}, 'admin');`);
out();

// authors
out('INSERT INTO authors (id, name, slug, designation, bio) VALUES');
out(authors.map((a, i) => `  (${i + 1}, ${e(a.name)}, ${e(a.slug)}, ${e(a.designation)}, ${e(a.bio)})`).join(',\n') + ';');
out();

// categories
out('INSERT INTO categories (id, name, slug, description, color, sort_order, show_on_home) VALUES');
out(categories.map((c, i) => `  (${i + 1}, ${e(c.name)}, ${e(c.slug)}, ${e(c.description)}, ${e(c.color)}, ${i + 1}, 1)`).join(',\n') + ';');
out();

// tags
const tagNames = [...new Set(articles.flatMap((a) => a.tags || []))];
const tagId = new Map(tagNames.map((t, i) => [t, i + 1]));
out('INSERT INTO tags (id, name, slug) VALUES');
out(tagNames.map((t, i) => `  (${i + 1}, ${e(t)}, ${e(slugify(t))})`).join(',\n') + ';');
out();

// media
const media = [];
const mediaId = new Map();
const addMedia = (key, row) => {
  if (mediaId.has(key)) return mediaId.get(key);
  const id = media.length + 1;
  media.push({ id, ...row });
  mediaId.set(key, id);
  return id;
};
for (const a of articles) {
  addMedia(a.image, {
    type: 'image', storage: 'local', url: `/uploads/seed/${a.image}.jpg`, original_name: `${a.image}.jpg`,
    mime_type: 'image/jpeg', width: 1600, height: 1000, alt_text: a.caption || a.title,
  });
  for (const [img, caption] of a.gallery || []) {
    addMedia(img, {
      type: 'image', storage: 'local', url: `/uploads/seed/${img}.jpg`, original_name: `${img}.jpg`,
      mime_type: 'image/jpeg', width: 1600, height: 1000, alt_text: caption,
    });
  }
  if (a.video?.type === 'upload') {
    addMedia(a.video.url, {
      type: 'video', storage: 'external', url: a.video.url, original_name: path.basename(a.video.url),
      mime_type: 'video/mp4', width: null, height: null, alt_text: 'Sample video',
    });
  }
}
out('INSERT INTO media (id, type, storage, url, original_name, mime_type, width, height, alt_text, uploaded_by) VALUES');
out(media.map((m) => `  (${m.id}, ${e(m.type)}, ${e(m.storage)}, ${e(m.url)}, ${e(m.original_name)}, ${e(m.mime_type)}, ${e(m.width)}, ${e(m.height)}, ${e(m.alt_text)}, 1)`).join(',\n') + ';');
out();

// articles
const catId = new Map(categories.map((c, i) => [c.slug, i + 1]));
const authorId = new Map(authors.map((a, i) => [a.slug, i + 1]));
const articleRows = articles.map((a, i) => {
  const content = sanitizeContent(a.content);
  const status = a.status || 'published';
  const videoType = a.video?.type || 'none';
  return `  (${[
    i + 1, e(a.title), e(slugify(a.title)), e(a.excerpt), e(content),
    mediaId.get(a.image), e(a.caption || null), catId.get(a.category), authorId.get(a.author),
    e(status), a.featured ? 1 : 0, a.editorsPick ? 1 : 0,
    e(videoType), e(videoType === 'embed' ? a.video.url : null), videoType === 'upload' ? mediaId.get(a.video.url) : 'NULL',
    readingTime(content), a.views || 0,
    e(a.title), e(a.excerpt),
    status === 'published' ? `UTC_TIMESTAMP() - INTERVAL ${a.hoursAgo || 1} HOUR` : 'NULL',
    1, 1,
  ].join(', ')})`;
});
out(`INSERT INTO articles (id, title, slug, excerpt, content, featured_media_id, featured_image_caption, category_id, author_id,
  status, is_featured, is_editors_pick, video_type, video_url, video_media_id, reading_time, views,
  meta_title, meta_description, published_at, created_by, updated_by) VALUES`);
out(articleRows.join(',\n') + ';');
out();

// article_tags
const at = articles.flatMap((a, i) => (a.tags || []).map((t) => `  (${i + 1}, ${tagId.get(t)})`));
out('INSERT INTO article_tags (article_id, tag_id) VALUES');
out(at.join(',\n') + ';');
out();

// article_media (gallery)
const am = articles.flatMap((a, i) => (a.gallery || []).map(([img, caption], idx) => `  (${i + 1}, ${mediaId.get(img)}, ${idx}, ${e(caption)})`));
if (am.length) {
  out('INSERT INTO article_media (article_id, media_id, sort_order, caption) VALUES');
  out(am.join(',\n') + ';');
  out();
}

out('COMMIT;');
fs.writeFileSync(OUT, lines.join('\n') + '\n');
console.log(`Wrote ${OUT} (${articles.length} articles, ${categories.length} categories, ${tagNames.length} tags, ${media.length} media)`);
